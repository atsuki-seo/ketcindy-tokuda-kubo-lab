// @title ナイキスト軌跡
Ketinit();
// ==========================================
// 【曲線の倍率】
// ==========================================
Slider("D",[0.025,4],[9,4]);
K = 5*D.x;
// ==========================================
// 【1. 伝達関数 G(s) の定義】
// ==========================================
Text0.xy=[2,-4];
Expr([[1.68,-4],"w","G(s)="]);
// テキストボックスの初期値
subsedit(0,"0");
str = Textedit(0,"");
//G(s) := parse(str);
G(s) := 1/((s+1)*(s+2)*(s+3)*(s+4));
// ==========================================
// 【画面の設定】
// ==========================================
Setwindow([-5,5],[-5,5]);
Setax(["l","Re","e","Im","n","O","sw"]);

//G(s) := 4 / ((1+s)*(2+s));
// ==========================================
// 【2. 周波数応答の定義】
// ==========================================
// s = jω
Gjw(w) := G(i*w);
// 実部
ReVal(w) := re(Gjw(w));
// 虚部
ImVal(w) := im(Gjw(w));
// ゲイン
Gain(w) := abs(Gjw(w));
// 位相差 [rad]
Phaserad(w) := arctan2(Gjw(w));
// 位相差 [deg]
Phasedeg(w) := Phaserad(w) * 180 / pi;

// ==========================================
// 【3. 計算と出力】
// ==========================================
w = 1;
compVal = Gjw(w);
rVal = ReVal(w);
iVal = ImVal(w);
println("======================================");
println("    【 周波数応答の計算結果 】");
println("======================================");
println("  設定角周波数 (w) : " + w + " [rad/s]");
println("--------------------------------------");
println("  複素数 G(jw)    : "
       + format(rVal,6)
       + " + "
       + format(iVal,6)
       + " j");
println("  実部 Re[G(jw)]  : "
       + format(rVal,6));
println("  虚部 Im[G(jw)]  : "
       + format(iVal,6));
println("--------------------------------------");
println("  位相差 (rad)    : "
       + format(Phaserad(w),6)
       + " rad");
println("======================================");

// ==========================================
// 【4. ゲインと位相差】
// ==========================================
magPlot = Gain(w);
phasePlot = Phasedeg(w);
// ==========================================
// 【5. ナイキスト軌跡の座標リストを作成】
// ==========================================
ptList = [];

// ------------------------------------------
// ω = 0 ～ 15
// 0.01刻みで計算
// ------------------------------------------
forall(0..1500,k,
 // 角周波数
 wk = k / 100;

 // G(jω)の実部・虚部
 rx = ReVal(wk);
 iy = ImVal(wk);

 // ========================================
 // 正常な実数の場合のみ追加
 // ========================================
 if(isreal(rx) & isreal(iy),
   // 画面範囲内の場合のみ追加
   if(abs(rx) <= 3 & abs(iy) <= 3,
     ptList = append(
       ptList,
       [rx,iy]
     );
   );
 );
);
// ==========================================
// 【6. ナイキスト軌跡を描画】
// ==========================================
// 座標を K 倍してから青い線で描画
ptList=apply(ptList,K*#);
Listplot(
 "phasor",
 ptList,
 ["dr,4","Color=blue"]
);
// ==========================================
// 【9. スライダーバー】
// ==========================================
// ω = 0.1 ～ 5
Slider(
 "C",
 [0.1,-2.8],
 [5,-2.8]
);

// ==========================================
// 【10. スライダーからωを取得】
// ==========================================
wSlider = C.x;

// ==========================================
// 【11. スライダーのωに対応するG(jω)】
// ==========================================
// 実部
xSlider = ReVal(wSlider);
// 虚部
ySlider = ImVal(wSlider);

// ==========================================
// 【12. 青い軌跡上を動く赤い点】
// ==========================================
// 赤い点の座標
pSlider = [xSlider,ySlider];
Putpoint("AA",[10,10]);
AA.xy=pSlider*K;

//println(sgsliderPoint);
//pointdata("1",AA,["Size=5","Color=red"]);
// ==========================================
// 【13. スライダー位置のゲイン・位相差】
// ==========================================
magSlider = Gain(wSlider);
phaseSlider = Phasedeg(wSlider);
Letter(
 [-3,2.7],
 "e",
 "|G(jw)| = " + format(magSlider,2)
);
Letter(
 [-3,2.4],
 "e",
 "∠G(jw) = " + format(phaseSlider,2) + "°"
);

// ==========================================
// 【14. 軌跡の始点（ω = 0）】
// ==========================================
// G(s) が s = 0 で無限大になる場合は w0 = 0.01 などにする
w0 = 0;
crossList = [[w0, ReVal(w0)]];

// ==========================================
// 【15. 座標メモリ（始点を追加）】
// ==========================================
// 目盛りの位置は K 倍、ラベルは実際の値
memori  = [K,"n3",1, -1*K,"n3",-1];
memori2 = [K,"w3",1, -1*K,"w3",-1];
forall(crossList, cp,
 xc = cp_2;
 memori = concat(memori, [K*xc, "s3", format(xc,4)]);
);
Htickmark(memori);
Vtickmark(memori2);
// 始点に点を打つ
if(length(crossList) > 0,
 Pointdata("cross", apply(crossList, [K*#_2, 0]), ["Size=4","Color=red"]);
);
// 始点の値を画面に表示
forall(1..length(crossList), n,
 Letter(
   [-3, 2.1-0.3*(n-1)],
   "e",
   "始点 = " + format(crossList_n_2,4)
   + "  (w = " + format(crossList_n_1,3) + ")"
 );
);

// ==========================================
// 【16. 描画】
// ==========================================
Windispg();
